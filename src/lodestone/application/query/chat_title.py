from __future__ import annotations

import re

from kag.common.llm.bedrock_claude_client import BedrockClaudeClient
from src.lodestone.config.settings import Settings

_MAX_ANSWER_CHARS = 600
_MAX_TITLE_CHARS = 48


def _fallback_title(query: str, answer: str) -> str:
    """Heuristic title when the LLM call fails."""
    q = query.strip()
    if len(q) >= 20:
        return _clip(q)
    if answer:
        plain = re.sub(r"[#*_`>\[\]]", "", answer)
        plain = re.sub(r"\s+", " ", plain).strip()
        for sentence in re.split(r"[.!?\n]", plain):
            sentence = sentence.strip()
            if len(sentence) >= 8:
                return _clip(sentence)
    if len(q) >= 2:
        return _clip(q[0].upper() + q[1:])
    return "New chat"


def _clip(text: str) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    if len(text) <= _MAX_TITLE_CHARS:
        return text
    return text[: _MAX_TITLE_CHARS - 1].rstrip() + "…"


def _sanitize_title(raw: str) -> str:
    title = raw.strip().strip("\"'").split("\n", 1)[0].strip()
    title = re.sub(r"\s+", " ", title)
    title = title.rstrip(".!?")
    return _clip(title) if title else "New chat"


def _build_prompt(messages: list[dict[str, str]]) -> str:
    lines = [
        "You label chat conversations for a sidebar.",
        "Read the exchange below and reply with ONLY a short, specific title:",
        "- 3 to 6 words",
        "- No quotes",
        "- No trailing punctuation",
        "- Name the topic discussed, not the format",
        "- For greetings or small talk, use a simple label like 'Greeting' or 'Getting started'",
        "",
    ]
    for idx, msg in enumerate(messages, start=1):
        query = msg.get("query", "").strip()
        answer = msg.get("answer", "").strip()
        if len(answer) > _MAX_ANSWER_CHARS:
            answer = answer[:_MAX_ANSWER_CHARS].rstrip() + "…"
        lines.append(f"Turn {idx}")
        lines.append(f"User: {query}")
        if answer:
            lines.append(f"Assistant: {answer}")
        lines.append("")
    lines.append("Title:")
    return "\n".join(lines)


async def generate_chat_title(messages: list[dict[str, str]], settings: Settings) -> str:
    """Return a short sidebar title for a chat, generated by the configured LLM."""
    if not messages:
        return "New chat"

    first = messages[0]
    fallback = _fallback_title(first.get("query", ""), first.get("answer", ""))

    llm = BedrockClaudeClient(
        region=settings.bedrock_region,
        model=settings.llm_model,
        temperature=0.2,
        max_tokens=32,
        name=f"chat_title:{settings.bedrock_region}:{settings.llm_model}",
    )
    try:
        raw = await llm.acall(prompt=_build_prompt(messages))
        title = _sanitize_title(raw)
        return title if title != "New chat" else fallback
    except Exception:
        return fallback
