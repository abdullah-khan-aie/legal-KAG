import logging

from openai import AsyncOpenAI, OpenAI

from kag.interface.common.llm_client import LLMClient
from kag.interface.solver.reporter_abc import do_report

logging.getLogger("openai").setLevel(logging.ERROR)
logging.getLogger("httpx").setLevel(logging.ERROR)
logger = logging.getLogger(__name__)


@LLMClient.register("azure_openai")
class AzureOpenAIClient(LLMClient):
    def __init__(
        self,
        api_key: str,
        base_url: str,
        model: str,
        stream: bool = False,
        temperature: float = 0.7,
        timeout: float = None,
        max_rate: float = 1000,
        time_period: float = 1,
        **kwargs,
    ):
        """Initialize the Azure OpenAI client (v1 API surface).

        We target the Azure OpenAI **v1 API**, which uses the standard OpenAI
        client pointed at a ``base_url`` ending in ``/openai/v1/`` with no
        ``api-version`` (the deployment name is passed as ``model``). This is
        NOT the classic data-plane API (``AzureOpenAI`` + ``api_version`` +
        ``azure_deployment``).

        Args:
            api_key: Azure OpenAI API key.
            base_url: Endpoint URL ending in ``/openai/v1/``.
            model: The deployment name (passed as ``model`` on the v1 API).
            stream: Whether to stream the response.
            temperature: Sampling temperature for the model.
            timeout: Request timeout; None means no timeout.
            max_rate: Maximum number of requests allowed per time period.
            time_period: Length of the rate-limiting window in seconds.
        """
        name = kwargs.pop("name", None)
        if not name:
            name = f"{api_key}{base_url}{model}"
        super().__init__(name, max_rate, time_period, **kwargs)

        self.api_key = api_key
        self.base_url = base_url
        self.model = model
        self.stream = stream
        self.temperature = temperature
        self.timeout = timeout
        self.client = OpenAI(api_key=self.api_key, base_url=self.base_url)
        self.aclient = AsyncOpenAI(api_key=self.api_key, base_url=self.base_url)

        self.check()
        logger.debug(
            f"Initialize AzureOpenAIClient with rate limit {max_rate} every {time_period}s"
        )

    def __call__(self, prompt: str = "", image_url: str = None, **kwargs):
        """Run a synchronous model request and return the result.

        Args:
            prompt: The prompt provided to the model.
            image_url: Optional image URL to include in the request.

        Returns:
            The response content generated by the model, or the full message
            object when tool calls are returned.
        """
        # Call the model with the given prompt and return the response
        tools = kwargs.get("tools", None)
        messages = kwargs.get("messages", None)
        token_meter = LLMClient.get_token_meter()
        if messages is None:
            if image_url:
                messages = [
                    {"role": "system", "content": "you are a helpful assistant"},
                    {
                        "role": "user",
                        "content": [
                            {"type": "text", "text": prompt},
                            {"type": "image_url", "image_url": {"url": image_url}},
                        ],
                    },
                ]
            else:
                messages = [
                    {"role": "system", "content": "you are a helpful assistant"},
                    {"role": "user", "content": prompt},
                ]
        response = self.client.chat.completions.create(
            model=self.model,
            messages=messages,
            stream=self.stream,
            temperature=self.temperature,
            timeout=self.timeout,
            max_tokens=self.max_tokens,
        )
        token_meter.update(
            response.usage.completion_tokens,
            response.usage.prompt_tokens,
            response.usage.total_tokens,
        )

        rsp = response.choices[0].message.content
        do_report(rsp, "FINISH", **kwargs)
        tool_calls = response.choices[0].message.tool_calls
        if tools and tool_calls:
            return response.choices[0].message

        return rsp

    async def acall(self, prompt: str = "", image_url: str = None, **kwargs):
        """Run an asynchronous model request and return the result.

        Args:
            prompt: The prompt provided to the model.
            image_url: Optional image URL to include in the request.

        Returns:
            The response content generated by the model, or the full message
            object when tool calls are returned.
        """
        # Call the model with the given prompt and return the response
        tools = kwargs.get("tools", None)
        messages = kwargs.get("messages", None)
        token_meter = LLMClient.get_token_meter()
        if messages is None:
            if image_url:
                messages = [
                    {"role": "system", "content": "you are a helpful assistant"},
                    {
                        "role": "user",
                        "content": [
                            {"type": "text", "text": prompt},
                            {"type": "image_url", "image_url": {"url": image_url}},
                        ],
                    },
                ]

            else:
                messages = [
                    {"role": "system", "content": "you are a helpful assistant"},
                    {"role": "user", "content": prompt},
                ]
        response = await self.aclient.chat.completions.create(
            model=self.model,
            messages=messages,
            stream=self.stream,
            temperature=self.temperature,
            timeout=self.timeout,
            max_tokens=self.max_tokens,
        )
        token_meter.update(
            response.usage.completion_tokens,
            response.usage.prompt_tokens,
            response.usage.total_tokens,
        )

        rsp = response.choices[0].message.content
        tool_calls = response.choices[0].message.tool_calls
        do_report(rsp, "FINISH", **kwargs)
        if tools and tool_calls:
            return response.choices[0].message
        return rsp

    async def astream(self, prompt: str = "", image_url: str = None, **kwargs):
        """Stream the model response as text deltas via Azure OpenAI streaming.

        Async generator that issues a ``stream=True`` chat completion and yields
        each ``choices[0].delta.content`` as it arrives. Token usage is metered
        from the final chunk (``stream_options={"include_usage": True}``).

        Args:
            prompt: The prompt provided to the model.
            image_url: Optional image URL to include in the request.

        Yields:
            str: The next text delta from the model.
        """
        messages = kwargs.get("messages", None)
        token_meter = LLMClient.get_token_meter()
        if messages is None:
            if image_url:
                messages = [
                    {"role": "system", "content": "you are a helpful assistant"},
                    {
                        "role": "user",
                        "content": [
                            {"type": "text", "text": prompt},
                            {"type": "image_url", "image_url": {"url": image_url}},
                        ],
                    },
                ]
            else:
                messages = [
                    {"role": "system", "content": "you are a helpful assistant"},
                    {"role": "user", "content": prompt},
                ]
        stream = await self.aclient.chat.completions.create(
            model=self.model,
            messages=messages,
            stream=True,
            temperature=self.temperature,
            timeout=self.timeout,
            max_tokens=self.max_tokens,
            stream_options={"include_usage": True},
        )
        async for chunk in stream:
            if chunk.choices:
                delta = chunk.choices[0].delta.content
                if delta:
                    yield delta
            usage = getattr(chunk, "usage", None)
            if usage:
                token_meter.update(
                    usage.completion_tokens, usage.prompt_tokens, usage.total_tokens
                )
