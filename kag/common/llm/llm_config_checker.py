import json


class LLMConfigChecker:
    """Check whether an LLM config is valid."""

    @staticmethod
    def check(config: str) -> str:
        """Validate an LLM config by issuing a test request.

        Args:
            config: LLM config as a JSON string.

        Returns:
            The text generated by the configured LLM.

        Raises:
            RuntimeError: If the config is invalid.
        """
        from kag.interface import LLMClient

        config = json.loads(config)
        llm_client = LLMClient.from_config(config)
        try:
            res = llm_client("who are you?")
            return res
        except Exception as ex:
            raise RuntimeError(f"invalid llm config: {config}, for details: {ex}")


